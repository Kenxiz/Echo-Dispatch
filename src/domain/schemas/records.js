import { z } from "zod";
import { plateSchema } from "./shared.js";

export const boloSchema = z.object({
  id: z.string(),
  type: z.enum(["PERSON", "VEHICLE"]),
  status: z.enum(["ACTIVE", "CANCELLED", "EXPIRED"]).default("ACTIVE"),
  nameOrAlias: z.string().max(150).nullable().default(null),
  sex: z.string().max(50).nullable().default(null),
  race: z.string().max(80).nullable().default(null),
  approximateAge: z.string().max(80).nullable().default(null),
  height: z.string().max(80).nullable().default(null),
  weightOrBuild: z.string().max(100).nullable().default(null),
  hair: z.string().max(100).nullable().default(null),
  clothing: z.string().max(250).nullable().default(null),
  distinguishingFeatures: z.string().max(250).nullable().default(null),
  color: z.string().max(50).nullable().default(null),
  make: z.string().max(80).nullable().default(null),
  model: z.string().max(80).nullable().default(null),
  vehicleType: z.string().max(80).nullable().default(null),
  approximateYear: z.string().max(20).nullable().default(null),
  doors: z.number().int().min(1).max(10).nullable().default(null),
  damage: z.string().max(250).nullable().default(null),
  occupantCount: z.number().int().nonnegative().nullable().default(null),
  plate: plateSchema.nullable().default(null),
  lastKnownLocation: z.string().max(250).nullable().default(null),
  directionOfTravel: z.string().max(100).nullable().default(null),
  travelMode: z.enum(["ON_FOOT", "VEHICLE", "UNKNOWN"]).default("UNKNOWN"),
  threatInformation: z.string().max(300).nullable().default(null),
  wantedReason: z.string().max(300).nullable().default(null),
  issuingUnit: z.string().max(30),
  callId: z.string().nullable().default(null),
  rawDescription: z.string().min(1).max(1000),
  createdAt: z.string().datetime(),
  updatedAt: z.string().datetime(),
  expiresAt: z.string().datetime().nullable().default(null),
  cancelledAt: z.string().datetime().nullable().default(null),
});

export const warrantSchema = z.object({
  id: z.string(),
  subjectType: z.enum(["PERSON", "VEHICLE"]),
  subjectName: z.string().max(150).nullable().default(null),
  vehicleDescription: z.string().max(250).nullable().default(null),
  plate: plateSchema.nullable().default(null),
  warrantType: z.string().min(1).max(100),
  chargesOrReason: z.string().min(1).max(300),
  issuingUnit: z.string().max(30),
  callId: z.string().nullable().default(null),
  status: z.enum(["ACTIVE", "CLEARED"]).default("ACTIVE"),
  threatFlags: z.array(z.string().max(150)).default([]),
  cautionFlags: z.array(z.string().max(150)).default([]),
  notes: z.array(z.string().max(300)).default([]),
  createdAt: z.string().datetime(),
  clearedAt: z.string().datetime().nullable().default(null),
  clearingUnit: z.string().max(30).nullable().default(null),
});

export const archivedRecordSchema = z.object({
  id: z.string(),
  dataset: z.enum(["units", "calls", "transmissions", "bolos", "warrants"]),
  identity: z.string(),
  reason: z.string().max(300),
  archivedAt: z.string().datetime(),
  record: z.record(z.string(), z.unknown()),
});
